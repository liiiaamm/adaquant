from __future__ import annotations

from dataclasses import dataclass
from typing import Optional

import boto3
from botocore.exceptions import ClientError


######## Naming helpers #########
def make_database_name(group: str) -> str:
    # required: trade_data_<grupo>
    group = group.strip()
    return f"trade_data_{group}"


def normalize_crypto_name(crypto: str) -> str:
    ##table names contain crypto reference
    return crypto.strip().lower().replace(" ", "_").replace("-", "_")


def make_crawler_name(group: str, crypto: str) -> str:
    ##representative name including crypto & group
    return f"crawler_{make_database_name(group)}_{normalize_crypto_name(crypto)}"


####### Glue managers #######
@dataclass(frozen=True)
class GlueConfig:
    region: str
    group: str
    bucket_name: str
    glue_role_arn: str


class GlueDatabaseManager:
    """Create/ensure Glue Catalog database trade_data_<group>."""

    def __init__(self, config: GlueConfig, glue_client=None):
        self.config = config
        self.glue = glue_client or boto3.client("glue", region_name=config.region)

    @property
    def database_name(self) -> str:
        return make_database_name(self.config.group)

    def ensure_database(self, description: Optional[str] = None, verbose: bool = False) -> None:
        try:
            self.glue.get_database(Name=self.database_name)
            if verbose:
                print(f"Glue database already exists: {self.database_name}")
            return
        except self.glue.exceptions.EntityNotFoundException:
            pass

        if verbose:
            print(f"Creating Glue database: {self.database_name}")

        self.glue.create_database(
            DatabaseInput={
                "Name": self.database_name,
                "Description": description or f"ADAQuant trade data catalog for group {self.config.group}",
            }
        )


class GlueCrawlerManager:
    """
    Create/ensure and run a Glue Crawler pointing at:
        s3://<bucket>/<crypto>/

    Tables generated by the crawler will live in:
        database trade_data_<group>
    """

    def __init__(self, config: GlueConfig, glue_client=None):
        self.config = config
        self.glue = glue_client or boto3.client("glue", region_name=config.region)

    def _s3_target_path(self, crypto: str) -> str:
        crypto = normalize_crypto_name(crypto)
        return f"s3://{self.config.bucket_name}/{crypto}/"

    def ensure_crawler(
        self,
        crypto: str,
        table_prefix: Optional[str] = None,
        verbose: bool = False,
    ) -> str:
        """
        Ensures the crawler exists. Returns crawler name.
        table_prefix: optional prefix for table names (still include crypto!)
        """
        crypto_norm = normalize_crypto_name(crypto)
        crawler_name = make_crawler_name(self.config.group, crypto_norm)

        ##Ensure table_prefix includes crypto reference
        if table_prefix is None:
            table_prefix = f"{crypto_norm}_"
        else:
            if crypto_norm not in table_prefix.lower():
                table_prefix = f"{crypto_norm}_{table_prefix}"

        target_path = self._s3_target_path(crypto_norm)
        db_name = make_database_name(self.config.group)

        try:
            self.glue.get_crawler(Name=crawler_name)
            if verbose:
                print(f"Crawler already exists: {crawler_name}. Updating targets/prefix just in case.")
            ## Update to keep aligned with config
            self.glue.update_crawler(
                Name=crawler_name,
                Role=self.config.glue_role_arn,
                DatabaseName=db_name,
                Targets={"S3Targets": [{"Path": target_path}]},
                TablePrefix=table_prefix,
            )
            return crawler_name
        except self.glue.exceptions.EntityNotFoundException:
            pass

        if verbose:
            print(f"Creating crawler: {crawler_name}")
            print(f"  Database: {db_name}")
            print(f"  Target:   {target_path}")
            print(f"  Prefix:   {table_prefix}")

        self.glue.create_crawler(
            Name=crawler_name,
            Role=self.config.glue_role_arn,
            DatabaseName=db_name,
            Targets={"S3Targets": [{"Path": target_path}]},
            TablePrefix=table_prefix,
            Description=f"ADAQuant crawler for {crypto_norm} ({self.config.group})",
        )
        return crawler_name

    def start_crawler(self, crawler_name: str, verbose: bool = False) -> None:
        """Starts the crawler on demand."""
        try:
            self.glue.start_crawler(Name=crawler_name)
            if verbose:
                print(f"Started crawler: {crawler_name}")
        except self.glue.exceptions.CrawlerRunningException:
            if verbose:
                print(f"Crawler already running: {crawler_name}")
        except ClientError as e:
            raise

    def wait_until_ready(self, crawler_name: str, poll_seconds: int = 10, verbose: bool = False) -> None:
        """
        Optional: waits until crawler state is READY.
        (Simple polling; good enough for scripts.)
        """
        import time

        while True:
            crawler = self.glue.get_crawler(Name=crawler_name)["Crawler"]
            state = crawler.get("State")
            if verbose:
                print(f"Crawler state: {state}")
            if state == "READY":
                return
            time.sleep(poll_seconds)


class AdaquantGlueCatalogOrchestrator:
    """Convenience orchestrator: ensure DB + ensure crawler + run crawler."""

    def __init__(self, config: GlueConfig, glue_client=None):
        self.config = config
        self.db = GlueDatabaseManager(config, glue_client=glue_client)
        self.crawlers = GlueCrawlerManager(config, glue_client=glue_client)

    def ensure_and_run(
        self,
        crypto: str,
        *,
        table_prefix: Optional[str] = None,
        wait: bool = False,
        verbose: bool = False,
    ) -> str:
        self.db.ensure_database(verbose=verbose)
        crawler_name = self.crawlers.ensure_crawler(crypto=crypto, table_prefix=table_prefix, verbose=verbose)
        self.crawlers.start_crawler(crawler_name, verbose=verbose)
        if wait:
            self.crawlers.wait_until_ready(crawler_name, verbose=verbose)
        return crawler_name
